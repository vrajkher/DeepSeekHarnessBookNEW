#!/usr/bin/env python3
"""Book tool: (re)write the reference-link block at the end of each chapter.

Chapters cite source as `[label][cite-id]`. This script finds every `[...][id]`
whose id exists in appendix/citations.generated.md and rewrites the block between
the markers below with `[id]: permalink` lines. It fails on an unknown id.

Usage: python3 tools/refdefs.py book/*.md appendix/*.md
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
TABLE = ROOT / 'appendix' / 'citations.generated.md'
BEGIN = '<!-- citations:begin (generated by tools/refdefs.py) -->'
END = '<!-- citations:end -->'

def load():
    links = {}
    for line in TABLE.read_text(encoding='utf-8').splitlines()[2:]:
        cells = [c.strip() for c in line.split('|')]
        cid = cells[1].strip('`')
        url = re.search(r'\]\((https://[^)]+)\)', cells[5]).group(1)
        links[cid] = url
    return links

def main():
    links = load()
    bad = 0
    for name in sys.argv[1:]:
        path = pathlib.Path(name)
        text = path.read_text(encoding='utf-8')
        body = text.split(BEGIN)[0].rstrip() + '\n'
        used = sorted(set(re.findall(r'\]\[([a-z0-9-]+)\]', body)))
        unknown = [u for u in used if u not in links]
        if unknown:
            print(f'{name}: unknown citation ids {unknown}', file=sys.stderr)
            bad += 1
            continue
        if not used:
            path.write_text(body, encoding='utf-8')
            continue
        block = '\n'.join(f'[{u}]: {links[u]}' for u in used)
        path.write_text(f'{body}\n{BEGIN}\n{block}\n{END}\n', encoding='utf-8')
    sys.exit(1 if bad else 0)

if __name__ == '__main__':
    main()
